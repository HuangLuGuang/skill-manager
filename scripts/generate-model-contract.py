"""Generate the Go transport copy of the canonical model switch contract."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "agent_manager/core/model_switch_contract.json"
body = source.read_text()
json.loads(body)
target = root / "scanner/internal/managedclient/model_contract_generated.go"
target.write_text('// Code generated by scripts/generate-model-contract.py; DO NOT EDIT.\n'
                  'package managedclient\n\nconst modelContractJSON = ' + json.dumps(body) + '\n')
