export const translatePhrase = (value, locale) => {
  if (locale !== 'en-US' || typeof value !== 'string') return value
  const trimmed = value.trim()
  if (enPhrases[trimmed]) return enPhrases[trimmed]
  const compactedChinese = trimmed.replace(/([\u3400-\u9fff])\s+(?=[\u3400-\u9fff])/g, '$1')
  return enPhrases[compactedChinese] || value
}
