import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const html = fs.readFileSync(path.join(root, 'src/index.html'), 'utf8')
const attributes = new Set(['placeholder', 'title', 'aria-label', 'alt'])
const voidTags = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr'])
const ignoredTags = new Set(['code', 'pre', 'script', 'style', 'textarea'])
const chinese = /[\u3400-\u9fff]/

const hashText = value => {
  let hash = 0x811c9dc5
  for (const character of String(value)) {
    hash ^= character.codePointAt(0)
    hash = Math.imul(hash, 0x01000193)
  }
  return (hash >>> 0).toString(36)
}

const rootNode = { selector: '', childNodes: 0, tags: new Map(), ignored: false }
const stack = [rootNode]
const bindings = []
const tokenPattern = /<!--[\s\S]*?-->|<![^>]*>|<\/?[^>]+>|[^<]+/g

for (const token of html.match(tokenPattern) || []) {
  const parent = stack.at(-1)
  if (token.startsWith('<!--') || token.startsWith('<!')) {
    parent.childNodes += 1
    continue
  }
  if (token.startsWith('</')) {
    if (stack.length > 1) stack.pop()
    continue
  }
  if (token.startsWith('<')) {
    const match = token.match(/^<\s*([a-zA-Z0-9-]+)/)
    if (!match) continue
    const tag = match[1].toLowerCase()
    parent.childNodes += 1
    const occurrence = (parent.tags.get(tag) || 0) + 1
    parent.tags.set(tag, occurrence)
    const id = token.match(/\sid=(["'])(.*?)\1/i)?.[2]
    const selector = id
      ? `#${id.replace(/([^\w-])/g, '\\$1')}`
      : parent.selector
        ? `${parent.selector}>${tag}:nth-of-type(${occurrence})`
        : `${tag}:nth-of-type(${occurrence})`
    const ignored = parent.ignored
      || ignoredTags.has(tag)
      || /\sdata-no-i18n(?:\s|=|>)/i.test(token)
    if (!ignored) {
      for (const attr of attributes) {
        const value = token.match(new RegExp(`\\s${attr}=(["'])(.*?)\\1`, 'i'))?.[2]?.trim()
        if (value && chinese.test(value)) {
          bindings.push({ selector, attribute: attr, key: `ui.${hashText(value)}`, source: value })
        }
      }
    }
    if (!voidTags.has(tag) && !token.endsWith('/>')) {
      stack.push({ selector, childNodes: 0, tags: new Map(), ignored })
    }
    continue
  }
  const nodeIndex = parent.childNodes
  parent.childNodes += 1
  const value = token.trim()
  if (value && chinese.test(value) && !parent.ignored) {
    bindings.push({ selector: parent.selector, nodeIndex, key: `ui.${hashText(value)}`, source: value })
  }
}

const output = `// Generated by scripts/generate-static-i18n-bindings.mjs.\nwindow.clientStaticI18nBindings = ${JSON.stringify(bindings, null, 2)}\n`
fs.writeFileSync(path.join(root, 'src/static-i18n-bindings.js'), output)
console.log(`Generated ${bindings.length} desktop static i18n bindings`)
